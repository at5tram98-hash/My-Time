CREATE TABLE IF NOT EXISTS enrollment (hash TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS device (id INTEGER PRIMARY KEY CHECK(id=1), hash TEXT NOT NULL, synced INTEGER, snapshot TEXT);
CREATE TABLE IF NOT EXISTS oauth (
  hash TEXT PRIMARY KEY, kind TEXT NOT NULL, expires INTEGER NOT NULL,
  challenge TEXT, refresh_group TEXT
);
CREATE TABLE IF NOT EXISTS proposals (
  id TEXT PRIMARY KEY, created INTEGER NOT NULL, status TEXT NOT NULL, payload TEXT NOT NULL
);
